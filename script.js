/* GOOGLE MAPS */
/* ================================= */

function mapsUrl(q){

  return 'https://www.google.com/maps/search/?api=1&query='
    + encodeURIComponent(
      q + ' Sausal La Libertad'
    );

}


/* ================================= */
/* CAMBIAR CATEGORÍA */
/* ================================= */

function showCategory(cat){

  if(!places[cat]){
    return;
  }

  current = cat;

  const m = meta[cat];

  $('#currentLabel').textContent = m[0];

  $('#currentTitle').textContent = m[1];

  $('#currentDesc').textContent = m[2];

  $('#localSearch').value = '';

  $$('.category-card').forEach(
    b => b.classList.toggle(
      'active',
      b.dataset.cat === cat
    )
  );

  render();

  document
    .querySelector('#mapa')
    .scrollIntoView({
      behavior:'smooth',
      block:'start'
    });

}


/* ================================= */
/* MOSTRAR TARJETAS */
/* ================================= */

function render(){

  const q =
    $('#localSearch')
      .value
      .trim()
      .toLowerCase();


  const list =
    places[current].filter(
      p =>
        (
          p.name +
          ' ' +
          p.desc +
          ' ' +
          p.location
        )
        .toLowerCase()
        .includes(q)
    );


  $('#cards').innerHTML =
    list.map(
      (p,i) => `

        <article class="place-card">

          <div class="place-cover">
            <span>${p.icon}</span>
          </div>

          <div class="place-body">

            <small>
              ${meta[current][1]}
            </small>

            <h3>
              ${p.name}
            </h3>

            <p>
              ${p.desc}
            </p>

            <div class="place-actions">

              <button
                data-detail="${i}"
              >
                Historia
              </button>

              <a
                class="maps"
                href="${mapsUrl(p.maps)}"
                target="_blank"
                rel="noopener"
              >
                📍 Maps
              </a>

            </div>

          </div>

        </article>

      `
    ).join('');


  $('#empty').classList.toggle(
    'hidden',
    list.length !== 0
  );


  $$('[data-detail]').forEach(
    btn => {

      btn.addEventListener(
        'click',
        () => {

          openModal(
            list[
              Number(
                btn.dataset.detail
              )
            ]
          );

        }
      );

    }
  );

}


