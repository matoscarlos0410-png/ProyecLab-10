function globalSearch(){

  const q =
    $('#globalSearch')
      .value
      .trim()
      .toLowerCase();

  const box =
    $('#globalResults');


  if(!q){

    box.classList.add(
      'hidden'
    );

    box.innerHTML = '';

    return;

  }


  let out = [];


  for(
    const [cat,list]
    of Object.entries(places)
  ){

    for(
      const p of list
    ){

      if(
        (
          p.name +
          ' ' +
          p.desc +
          ' ' +
          p.location +
          ' ' +
          meta[cat][1]
        )
        .toLowerCase()
        .includes(q)
      ){

        out.push({
          cat,
          p
        });

      }

    }

  }


  box.innerHTML =
    out
      .slice(0,8)
      .map(
        x => `

          <div class="global-result">

            <div>

              <b>
                ${x.p.icon}
                ${x.p.name}
              </b>

              <span>
                ${meta[x.cat][1]}
                ·
                ${x.p.location}
              </span>

            </div>

            <a
              href="${mapsUrl(x.p.maps)}"
              target="_blank"
              rel="noopener"
            >
              Maps →
            </a>

          </div>

        `
      )
      .join('')

    ||

    '<div class="global-result">No encontramos coincidencias. Prueba con otra palabra.</div>';


  box.classList.remove(
    'hidden'
  );

}


