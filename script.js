/* NAVEGACIÓN AUTOMÁTICA */
/* ================================= */

const sections =
  $$('main section[id]');

const navLinks =
  $$('#nav a');


const observer =
  new IntersectionObserver(

    entries =>

      entries.forEach(

        e => {

          if(
            e.isIntersecting
          ){

            navLinks.forEach(

              a =>

                a.classList.toggle(
                  'active',
                  a.getAttribute(
                    'href'
                  ) ===
                  '#' +
                  e.target.id
                )

            );

          }

        }

      ),

    {
      rootMargin:
        '-30% 0px -55%'
    }

  );


sections.forEach(
  s => observer.observe(s)
);


